import test from 'node:test';
import assert from 'node:assert/strict';
import {TABLES,columnSQL,insertSQL,createSQL,exportSQL} from '../netlify/functions/sql-export.mjs';
const col=(table,name,type='bigint',extra={})=>({
 table_name:table,column_name:name,data_type:type,
 is_required:name==='id',identity_kind:name==='id'?'d':'',
 generated_kind:'',default_expr:null,...extra
});
function dbMock(){
 const columns=TABLES.flatMap(t=>
  [col(t,'id'),...(t==='properties'?[col(t,'name','text')]:
    t==='room_types'?[col(t,'property_id'),col(t,'name','text')]:
    t==='property_photos'?[col(t,'property_id'),col(t,'image_url','text')]:[])]);
 return {async query(sql){
  if(sql.includes('format_type('))return {rows:columns};
  if(sql.includes('pg_get_constraintdef('))return {rows:[
   {table_name:'properties',constraint_name:'properties_pkey',definition:'PRIMARY KEY (id)'},
   {table_name:'room_types',constraint_name:'room_types_property_id_fkey',definition:'FOREIGN KEY (property_id) REFERENCES properties(id)'}
  ]};
  if(sql.includes('pg_get_indexdef('))return {rows:[]};
  if(sql.includes('FROM public."properties"'))return {rows:[{v0:'1',v1:"'Sample Hotel'"}]};
  if(sql.includes('FROM public."room_types"'))return {rows:[{v0:'2',v1:'1',v2:"'Studio'"}]};
  if(sql.includes('FROM public."property_photos"'))return {rows:[{v0:'3',v1:'1',v2:"'https://example.com/photo.jpg'"}]};
  throw new Error('Unexpected SQL: '+sql);
 }};
}
test('export lists all 11 expected database tables',()=>assert.equal(TABLES.length,11));
test('identity columns are restorable and preserve explicit seed IDs',()=>{
 assert.match(columnSQL(col('properties','id')),/GENERATED BY DEFAULT AS IDENTITY/);
 assert.match(insertSQL('properties',[col('properties','id')],['5']),/VALUES \(5\)/);
});
test('creates a SQL schema with constraints and safe seed tables only',async()=>{
 const sql=await createSQL(dbMock());
 assert.equal((sql.match(/^CREATE TABLE /gm)||[]).length,11);
 assert.match(sql,/ALTER TABLE "room_types" ADD CONSTRAINT/);
 assert.match(sql,/INSERT INTO public\."properties"/);
 assert.match(sql,/INSERT INTO public\."room_types"/);
 assert.match(sql,/INSERT INTO public\."property_photos"/);
 for(const table of TABLES.filter(t=>!['properties','room_types','property_photos'].includes(t)))
  assert.ok(!sql.includes('INSERT INTO public."'+table+'"'));
 assert.match(sql,/COMMIT;/);
 assert.match(sql,/setval/);
});
test('export has SQL attachment header and never contains private example data',async()=>{
 const res=await exportSQL(dbMock());
 assert.equal(res.status,200);
 assert.match(res.headers.get('Content-Disposition'),/\.sql/);
 assert.match(res.headers.get('Cache-Control'),/no-store/);
 const body=await res.text();
 assert.ok(!body.includes('secret@example.com'));
});
