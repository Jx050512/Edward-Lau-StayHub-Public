/* StayHub coursework SQL export: server-side, MFA-admin-only, privacy-safe.
 * Recreates 11 public schema tables plus public accommodation seed data.
 * Not a full production pg_dump or disaster-recovery backup.
 */
import {HttpError} from './core.mjs';

export const TABLES=['auth_attempts','booking_items','bookings','demo_payments',
 'login_challenges','notifications','properties','property_photos','room_types',
 'sessions','users'];
const SEED=['properties','property_photos','room_types'];
const MAX=5000;
const id=s=>'"'+String(s).replaceAll('"','""')+'"';
const lit=s=>"'"+String(s).replaceAll("'","''")+"'";

export function columnSQL(c){
 let suffix='';
 if(c.generated_kind==='s'){
  if(!c.default_expr)throw new HttpError(500,'Missing generated expression.');
  suffix=' GENERATED ALWAYS AS ('+c.default_expr+') STORED';
 }else if(c.identity_kind==='a'||c.identity_kind==='d'){
  suffix=' GENERATED '+(c.identity_kind==='a'?'ALWAYS':'BY DEFAULT')+' AS IDENTITY';
 }else if(/^nextval\s*\(/i.test(c.default_expr||'')){
  suffix=' GENERATED BY DEFAULT AS IDENTITY';
 }else if(c.default_expr){
  suffix=' DEFAULT '+c.default_expr;
 }
 return '  '+id(c.column_name)+' '+c.data_type+suffix+(c.is_required?' NOT NULL':'');
}
export function insertSQL(table,columns,values){
 const override=columns.some(c=>c.identity_kind==='a')?' OVERRIDING SYSTEM VALUE':'';
 return 'INSERT INTO public.'+id(table)+' ('+columns.map(c=>id(c.column_name)).join(', ')+
  ')'+override+' VALUES ('+values.join(', ')+');';
}

export async function createSQL(db){
 const colQuery=[
  'SELECT cl.relname AS table_name, a.attname AS column_name,',
  'format_type(a.atttypid,a.atttypmod) AS data_type,',
  'a.attnotnull AS is_required, a.attidentity AS identity_kind,',
  'a.attgenerated AS generated_kind,pg_get_expr(def.adbin,def.adrelid) AS default_expr',
  'FROM pg_class cl JOIN pg_namespace ns ON ns.oid=cl.relnamespace',
  'JOIN pg_attribute a ON a.attrelid=cl.oid AND a.attnum>0 AND NOT a.attisdropped',
  'LEFT JOIN pg_attrdef def ON def.adrelid=cl.oid AND def.adnum=a.attnum',
  "WHERE ns.nspname='public' AND cl.relkind='r' AND cl.relname=ANY($1::text[])",
  'ORDER BY cl.relname,a.attnum'
 ].join(' ');
 const colRows=(await db.query(colQuery,[TABLES])).rows;
 const columns=new Map(TABLES.map(name=>[name,[]]));
 for(const c of colRows)columns.get(c.table_name)?.push(c);
 if(TABLES.some(name=>!columns.get(name)?.length))
  throw new HttpError(500,'Expected database tables missing; SQL export requires review.');

 const constraints=(await db.query([
  'SELECT cl.relname AS table_name,con.conname AS constraint_name,',
  'pg_get_constraintdef(con.oid,true) AS definition',
  'FROM pg_constraint con JOIN pg_class cl ON cl.oid=con.conrelid',
  'JOIN pg_namespace ns ON ns.oid=cl.relnamespace',
  "WHERE ns.nspname='public' AND cl.relname=ANY($1::text[])",
  'ORDER BY cl.relname,con.contype,con.conname'
 ].join(' '),[TABLES])).rows;
 const indexes=(await db.query([
  'SELECT tbl.relname AS table_name,idx.relname AS index_name,',
  'pg_get_indexdef(ix.indexrelid) AS definition',
  'FROM pg_index ix JOIN pg_class tbl ON tbl.oid=ix.indrelid',
  'JOIN pg_namespace ns ON ns.oid=tbl.relnamespace',
  'JOIN pg_class idx ON idx.oid=ix.indexrelid',
  'LEFT JOIN pg_constraint con ON con.conindid=ix.indexrelid',
  "WHERE ns.nspname='public' AND tbl.relname=ANY($1::text[])",
  'AND con.oid IS NULL ORDER BY tbl.relname,idx.relname'
 ].join(' '),[TABLES])).rows;
 const lines=[
  '-- StayHub WMD1413 PostgreSQL coursework schema + public demo inventory',
  '-- Generated: '+new Date().toISOString(),
  '-- All 11 table structures, keys, checks and indexes; safe property/room seed rows only.',
  '-- Real accounts, bookings, OTPs, sessions, passwords, tokens and guest contacts are excluded.',
  '-- Coursework restore script, NOT an official pg_dump or full production backup.',
  'BEGIN;','SET search_path TO public;','SET standard_conforming_strings = on;',''
 ];
 for(const table of TABLES)
  lines.push('CREATE TABLE '+id(table)+' (\n'+columns.get(table).map(columnSQL).join(',\n')+'\n);','');

 // Ask PostgreSQL to quote values correctly for its native types (text, JSONB,
 // numeric, arrays and timestamps). No raw user strings are interpolated.
 for(const table of SEED){
  const cols=columns.get(table);
  const expr=cols.map((col,i)=>
   'quote_nullable('+id(col.column_name)+') AS '+id('v'+i)).join(', ');
  const rows=(await db.query('SELECT '+expr+' FROM public.'+id(table)+
   ' ORDER BY '+id('id')+' LIMIT '+(MAX+1))).rows;
  if(rows.length>MAX)throw new HttpError(413,'Too many public inventory records to export.');
  lines.push('-- '+table+': '+rows.length+' public rows');
  for(const row of rows)lines.push(insertSQL(table,cols,cols.map((_,i)=>row['v'+i])));
  lines.push('');
 }
 // Constraint creation after inserts avoids cross-table dependency ordering.
 for(const c of constraints)lines.push('ALTER TABLE '+id(c.table_name)+
  ' ADD CONSTRAINT '+id(c.constraint_name)+' '+c.definition+';');
 lines.push('');
 for(const index of indexes)lines.push(index.definition+';');
 lines.push('');
 // Explicit IDs do not advance identity sequences: adjust after seed insertion.
 for(const table of SEED){
  for(const col of columns.get(table).filter(c=>Boolean(c.identity_kind)||
   /^nextval\s*\(/i.test(c.default_expr||''))){
   const tableRef='public.'+id(table),field=id(col.column_name);
   lines.push('SELECT setval(pg_get_serial_sequence('+lit(tableRef)+','+
    lit(col.column_name)+')::regclass, COALESCE((SELECT MAX('+field+') FROM '+
    tableRef+'),1), EXISTS(SELECT 1 FROM '+tableRef+'));');
  }
 }
 lines.push('COMMIT;','');
 return lines.join('\n');
}

export async function exportSQL(db){
 const content=await createSQL(db);
 const filename='StayHub_Database_Submission_'+new Date().toISOString().slice(0,10)+'.sql';
 return new Response(content,{status:200,headers:{
  'Content-Type':'application/sql; charset=utf-8',
  'Content-Disposition':'attachment; filename="'+filename+'"',
  'Cache-Control':'private, no-store, max-age=0','Pragma':'no-cache',
  'X-Content-Type-Options':'nosniff',
  'Content-Security-Policy':"default-src 'none'; sandbox"
 }});
}
